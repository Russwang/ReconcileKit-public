CREATE TABLE import_batches (
    attempt_id UUID PRIMARY KEY,
    source VARCHAR(100) NOT NULL CHECK (source = BTRIM(source) AND LENGTH(source) BETWEEN 1 AND 100),
    content_hash VARCHAR(64) NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    outcome VARCHAR(16) NOT NULL CHECK (outcome IN ('COMMITTED', 'REJECTED', 'FAILED')),
    total INTEGER NOT NULL CHECK (total >= 0),
    inserted INTEGER NOT NULL CHECK (inserted >= 0),
    duplicate INTEGER NOT NULL CHECK (duplicate >= 0),
    not_imported INTEGER NOT NULL CHECK (not_imported >= 0),
    row_errors TEXT NOT NULL DEFAULT '[]',
    error_summary TEXT,
    request_id VARCHAR(100) NOT NULL CHECK (LENGTH(request_id) BETWEEN 1 AND 100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT import_batch_counts CHECK (
        (outcome = 'COMMITTED' AND total = inserted + duplicate AND not_imported = 0)
        OR (outcome IN ('REJECTED', 'FAILED') AND inserted = 0 AND duplicate = 0 AND not_imported = total)
    )
);

CREATE TABLE invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(100) NOT NULL CHECK (source = BTRIM(source) AND LENGTH(source) BETWEEN 1 AND 100),
    external_invoice_id VARCHAR(100) NOT NULL CHECK (external_invoice_id = BTRIM(external_invoice_id) AND LENGTH(external_invoice_id) BETWEEN 1 AND 100),
    amount NUMERIC(19,2) NOT NULL CHECK (amount > 0 AND amount <= 999999999999.99),
    currency VARCHAR(3) NOT NULL CHECK (currency = 'GBP'),
    issued_on DATE NOT NULL,
    first_batch_id UUID NOT NULL REFERENCES import_batches(attempt_id),
    source_row INTEGER NOT NULL CHECK (source_row > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT invoices_source_identity UNIQUE (source, external_invoice_id)
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(100) NOT NULL CHECK (source = BTRIM(source) AND LENGTH(source) BETWEEN 1 AND 100),
    external_payment_id VARCHAR(100) NOT NULL CHECK (external_payment_id = BTRIM(external_payment_id) AND LENGTH(external_payment_id) BETWEEN 1 AND 100),
    amount NUMERIC(19,2) NOT NULL CHECK (amount > 0 AND amount <= 999999999999.99),
    currency VARCHAR(3) NOT NULL CHECK (currency = 'GBP'),
    received_on DATE NOT NULL,
    raw_reference TEXT,
    target_invoice_source VARCHAR(100),
    target_external_invoice_id VARCHAR(100),
    first_batch_id UUID NOT NULL REFERENCES import_batches(attempt_id),
    source_row INTEGER NOT NULL CHECK (source_row > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT payments_source_identity UNIQUE (source, external_payment_id),
    CONSTRAINT payments_target_pair CHECK (
        (target_invoice_source IS NULL AND target_external_invoice_id IS NULL)
        OR (
            target_invoice_source IS NOT NULL AND target_external_invoice_id IS NOT NULL
            AND target_invoice_source = BTRIM(target_invoice_source) AND LENGTH(target_invoice_source) BETWEEN 1 AND 100
            AND target_external_invoice_id = BTRIM(target_external_invoice_id) AND LENGTH(target_external_invoice_id) BETWEEN 1 AND 100
        )
    )
);

CREATE TABLE allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id UUID NOT NULL,
    payment_id BIGINT NOT NULL REFERENCES payments(id),
    invoice_id BIGINT NOT NULL REFERENCES invoices(id),
    amount NUMERIC(19,2) NOT NULL CHECK (amount > 0 AND amount <= 999999999999.99),
    origin VARCHAR(16) NOT NULL CHECK (origin IN ('MANUAL', 'AUTO')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX allocations_payment_idx ON allocations(payment_id);
CREATE INDEX allocations_invoice_idx ON allocations(invoice_id);
CREATE INDEX allocations_operation_idx ON allocations(operation_id);

CREATE TABLE idempotency_records (
    operation_type VARCHAR(32) NOT NULL CHECK (LENGTH(operation_type) BETWEEN 1 AND 32),
    key VARCHAR(200) NOT NULL CHECK (LENGTH(key) BETWEEN 1 AND 200),
    request_hash VARCHAR(64) NOT NULL CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    operation_id UUID NOT NULL,
    response_status INTEGER CHECK (response_status BETWEEN 200 AND 299),
    response_body TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (operation_type, key),
    CONSTRAINT idempotency_response_pair CHECK ((response_status IS NULL) = (response_body IS NULL))
);
CREATE INDEX idempotency_operation_idx ON idempotency_records(operation_id);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id UUID NOT NULL,
    actor VARCHAR(16) NOT NULL CHECK (actor IN ('local', 'system')),
    event_type VARCHAR(100) NOT NULL CHECK (LENGTH(event_type) BETWEEN 1 AND 100),
    aggregate_id TEXT NOT NULL CHECK (LENGTH(aggregate_id) > 0),
    detail TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX audit_operation_idx ON audit_events(operation_id);
CREATE INDEX audit_aggregate_idx ON audit_events(aggregate_id, id);
